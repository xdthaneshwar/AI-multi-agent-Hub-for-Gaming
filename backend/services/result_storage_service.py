import json
from pathlib import Path
from typing import Any, Union
from backend.config import RESULTS_DIR

class ResultStorageService:
    """
    ResultStorageService handles persistent storage, retrieval, and verification
    of JSON result artifacts generated by AI Multi-Agent Hub modules.

    All artifacts are stored under results/<job_id>/<filename>.
    Supported standard artifacts include:
    - upload.json
    - analysis.json
    - highlights.json
    - seo.json
    - thumbnails.json
    - creator_brief.json
    """

    def _get_result_file_path(self, job_id: str, filename: str) -> Path:
        """
        Helper method to construct and sanitize the path to a result file.

        Args:
            job_id (str): Unique job identifier.
            filename (str): Target filename (e.g., 'analysis.json', 'seo.json').

        Returns:
            Path: Sanitized absolute path to the target JSON file.
        """
        safe_job_id = Path(job_id).name
        safe_filename = Path(filename).name
        return RESULTS_DIR / safe_job_id / safe_filename

    def save_result(self, job_id: str, filename: str, data: Any) -> None:
        """
        Saves data as a formatted JSON file under results/<job_id>/<filename>.
        Automatically creates missing parent directories.

        Args:
            job_id (str): Unique job identifier.
            filename (str): Target JSON filename.
            data (Any): Data payload (dict, list, etc.) to serialize.

        Raises:
            RuntimeError: If writing to disk fails or data cannot be serialized.
        """
        file_path = self._get_result_file_path(job_id, filename)

        try:
            # Create target parent directory automatically if it doesn't exist
            file_path.parent.mkdir(parents=True, exist_ok=True)

            with open(file_path, "w", encoding="utf-8") as f:
                json.dump(data, f, indent=4)
        except (OSError, TypeError) as e:
            raise RuntimeError(f"Failed to save result file '{file_path.name}' for job '{job_id}': {str(e)}")

    def load_result(self, job_id: str, filename: str) -> Union[dict, list, Any]:
        """
        Loads and parses a JSON result file for a specific job ID.

        Args:
            job_id (str): Unique job identifier.
            filename (str): Target JSON filename to read.

        Returns:
            Union[dict, list, Any]: Parsed JSON content.

        Raises:
            FileNotFoundError: If the result file does not exist.
            RuntimeError: If reading or parsing JSON fails.
        """
        file_path = self._get_result_file_path(job_id, filename)

        if not file_path.exists():
            raise FileNotFoundError(f"Result file '{filename}' not found for job '{job_id}'.")

        try:
            with open(file_path, "r", encoding="utf-8") as f:
                return json.load(f)
        except (json.JSONDecodeError, OSError) as e:
            raise RuntimeError(f"Failed to parse JSON result file '{filename}' for job '{job_id}': {str(e)}")

    def result_exists(self, job_id: str, filename: str) -> bool:
        """
        Checks whether a specific result JSON file exists and is valid.

        Args:
            job_id (str): Unique job identifier.
            filename (str): Target JSON filename.

        Returns:
            bool: True if the file exists and is a valid file, False otherwise.
        """
        file_path = self._get_result_file_path(job_id, filename)
        return file_path.exists() and file_path.is_file()
